import { AppError } from '../errors/safe-error';

/**
 * Where file contents live (plan 4.6). 0.4 delivers the interface and the filesystem adapter; there are no HTTP
 * routes: the module that owns a file serves it, after a permission check or with a short signed URL.
 */
export interface FileStorage {
  /** Stores `data` under `key`, replacing any earlier object. */
  put(key: string, data: Buffer, meta: { contentType: string }): Promise<void>;
  /** Throws AppError('file_not_found') when the key does not exist. */
  get(key: string): Promise<Buffer>;
  exists(key: string): Promise<boolean>;
  /** Idempotent: deleting a missing key is not an error. */
  delete(key: string): Promise<void>;
  /** A URL that works until `expiresInSeconds` have passed. */
  signedUrl(key: string, expiresInSeconds: number, now?: Date): string;
  /** Checks a signature taken from a signed URL. False when wrong, tampered or expired. */
  verifySignature(key: string, expiresAtEpochSeconds: number, signature: string, now?: Date): boolean;
}

export const FILE_STORAGE = Symbol('FILE_STORAGE');

const KEY = /^[a-z0-9][a-z0-9_\-./]{0,199}$/;

/** Keys are generated by the platform (never from a file name). This rejects anything that could escape the root. */
export function assertValidKey(key: string): void {
  if (!KEY.test(key) || key.includes('..') || key.includes('//') || key.endsWith('/') || key.split('/').some((s) => s.startsWith('.'))) {
    throw new AppError('file_key_invalid', 'The storage key is not valid');
  }
}
