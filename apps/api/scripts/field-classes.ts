import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseSchema } from '../test/conventions/schema-conventions';

export type FieldClass = 'pii' | 'nopii' | 'secret';

/**
 * Classifies every scalar column of every model from its `///` annotation (plan 1.3, 4.9): `@secret`, `@nopii`,
 * `@pii`; identifiers (`@id`, `@db.Uuid`, foreign-key columns) are `nopii`; anything else unannotated is `pii`.
 */
export function classifyFields(schemaDir: string): Record<string, Record<string, FieldClass>> {
  const files = readdirSync(schemaDir).filter((f) => f.endsWith('.prisma')).sort().map((f) => ({ name: f, text: readFileSync(join(schemaDir, f), 'utf8') }));
  const models = parseSchema(files);
  const modelNames = new Set(models.map((m) => m.name));
  const out: Record<string, Record<string, FieldClass>> = {};
  for (const m of [...models].sort((a, b) => a.name.localeCompare(b.name))) {
    const fk = new Set(m.fields.flatMap((f) => f.relation?.fields ?? []));
    const classes: Record<string, FieldClass> = {};
    for (const f of m.fields) {
      if (modelNames.has(f.type)) continue; // relation field, not a column
      if (/@secret\b/.test(f.doc)) classes[f.name] = 'secret';
      else if (/@nopii\b/.test(f.doc)) classes[f.name] = 'nopii';
      else if (/@pii\b/.test(f.doc)) classes[f.name] = 'pii';
      else if (/@id\b/.test(f.attrs) || /@db\.Uuid\b/.test(f.attrs) || fk.has(f.name)) classes[f.name] = 'nopii';
      else classes[f.name] = 'pii';
    }
    out[m.name] = classes;
  }
  return out;
}

export function renderFieldClasses(classes: Record<string, Record<string, FieldClass>>): string {
  return `// Generated by apps/api/scripts/gen-field-classes.ts from the /// annotations in prisma/schema. Do not edit.
// Regenerate with \`pnpm --filter @mt/api gen:field-classes\`; a test fails when this file is out of date.
export type FieldClass = 'pii' | 'nopii' | 'secret';

export const FIELD_CLASSES: Readonly<Record<string, Readonly<Record<string, FieldClass>>>> = ${JSON.stringify(classes, null, 2).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")};
`;
}
